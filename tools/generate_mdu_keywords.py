"""Generate ``model_input/mdu_keywords.py`` from the official MDU specification (D123).

The specification is ``specifications/dflowfm/mdu.json`` in
``Deltares/Delft3DFM.File.Specifications``. Its git blob SHA must equal the pinned
value below, so the generated module always states exactly which file it came from.

Usage (from the repository root)::

    python tools\\generate_mdu_keywords.py --spec <path to mdu.json>
    python tools\\generate_mdu_keywords.py --spec <path to mdu.json> --check

``--check`` regenerates the module in memory and fails when the file on disk differs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

SPEC_REPOSITORY = "Deltares/Delft3DFM.File.Specifications"
SPEC_PATH = "specifications/dflowfm/mdu.json"
SPEC_COMMIT = "fe15f64cbe559e520c7d51993b1fb5e6f75c876c"
SPEC_BLOB_SHA = "3a57da78ea8f8d311614d08a9456ea27e368416f"

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = REPO_ROOT / "src" / "d3dplot" / "model_input" / "mdu_keywords.py"

_LEADING_DIGITS = re.compile(r"\d+")
_DIGIT_WORDS = {
    "0": "zero",
    "1": "one",
    "2": "two",
    "3": "three",
    "4": "four",
    "5": "five",
    "6": "six",
    "7": "seven",
    "8": "eight",
    "9": "nine",
}
_STATUS_BY_SPEC_VALUE: dict[str | None, str] = {
    None: "standard",
    "research": "research",
    "deprecated": "deprecated",
    "obsolete": "obsolete",
}


def git_blob_sha(data: bytes) -> str:
    """Return the SHA-1 that git assigns to a file with these bytes."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def read_spec(path: Path) -> dict[str, Any]:
    """Read the specification and refuse any file that is not the pinned blob."""
    data = path.read_bytes()
    sha = git_blob_sha(data)
    if sha != SPEC_BLOB_SHA:
        raise SystemExit(
            f"{path} has blob SHA {sha}, expected {SPEC_BLOB_SHA} "
            f"({SPEC_REPOSITORY} {SPEC_PATH} at {SPEC_COMMIT})."
        )
    document: dict[str, Any] = json.loads(data.decode("utf-8"))
    return document


def normalise_name(name: str) -> str:
    """Mirror ``d3dplot.model_input.ini.normalise_key`` (a test checks they agree).

    The generator must not import the package, because the package imports the
    generated module.
    """
    match = _LEADING_DIGITS.match(name)
    if match:
        digits = "".join(_DIGIT_WORDS.get(char, char) for char in match.group())
        name = digits + name[match.end() :]
    return name.lower().replace(" ", "_").replace("-", "")


def collect_keywords(document: dict[str, Any]) -> dict[str, dict[str, tuple[str, str]]]:
    """Map section name to keyword to (value type, status), in specification order."""
    keywords: dict[str, dict[str, tuple[str, str]]] = {}
    seen_sections: set[str] = set()
    for section in document["ini_sections"]:
        section_name = section["name"]
        if not _is_identifier(normalise_name(section_name)):
            raise SystemExit(f"Section name {section_name!r} cannot match an MDU file.")
        if normalise_name(section_name) in seen_sections:
            raise SystemExit(f"Duplicate section in specification: {section_name}.")
        seen_sections.add(normalise_name(section_name))
        entries: dict[str, tuple[str, str]] = {}
        seen_keys: set[str] = set()
        for prop in section["ini_properties"]:
            key = prop["key"]
            if not _is_identifier(normalise_name(key)):
                raise SystemExit(f"Keyword {key!r} cannot match an MDU file.")
            if normalise_name(key) in seen_keys:
                raise SystemExit(f"Keyword {key} repeats in section {section_name}.")
            seen_keys.add(normalise_name(key))
            spec_status = (prop.get("status") or {}).get("value")
            if spec_status not in _STATUS_BY_SPEC_VALUE:
                raise SystemExit(f"Unknown status {spec_status!r} for {key}.")
            entries[key] = (prop["value_type"], _STATUS_BY_SPEC_VALUE[spec_status])
        keywords[section_name] = entries
    return keywords


def _is_identifier(text: str) -> bool:
    return re.fullmatch(r"[a-z_][a-z0-9_]*", text) is not None


def _quote(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render_module(keywords: dict[str, dict[str, tuple[str, str]]]) -> str:
    """Return the Python source of the keyword module."""
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        '"""Keywords of the D-Flow FM MDU file, from the official specification.',
        "",
        "Generated by tools/generate_mdu_keywords.py. Do not edit by hand.",
        "",
        f"Source: {SPEC_REPOSITORY}, {SPEC_PATH},",
        f"commit {SPEC_COMMIT},",
        f"blob {SPEC_BLOB_SHA}.",
        "The source is an internal Deltares repository. Its use here rests on the",
        "statement of a Deltares contributor that the file can be used (plan D123).",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from typing import Literal, NamedTuple",
        "",
        "from d3dplot.model_input.ini import normalise_key",
        "",
        'KeywordStatus = Literal["standard", "research", "deprecated", "obsolete"]',
        "",
        f"SPEC_COMMIT = {_quote(SPEC_COMMIT)}",
        f"SPEC_BLOB_SHA = {_quote(SPEC_BLOB_SHA)}",
        "",
        "",
        "class KeywordSpec(NamedTuple):",
        '    """Value type and status of one MDU keyword."""',
        "",
        "    value_type: str",
        "    status: KeywordStatus",
        "",
        "",
        "MDU_KEYWORDS: Mapping[str, Mapping[str, KeywordSpec]] = {",
    ]
    for section, entries in keywords.items():
        lines.append(f"    {_quote(section)}: {{")
        for key, (value_type, status) in entries.items():
            spec = f"KeywordSpec({_quote(value_type)}, {_quote(status)})"
            lines.append(f"        {_quote(key)}: {spec},")
        lines.append("    },")
    lines += [
        "}",
        "",
        "_BY_NORMALISED_NAME: Mapping[tuple[str, str], KeywordSpec] = {",
        "    (normalise_key(section), normalise_key(key)): spec",
        "    for section, entries in MDU_KEYWORDS.items()",
        "    for key, spec in entries.items()",
        "}",
        "_NORMALISED_SECTIONS = frozenset("
        "normalise_key(section) for section in MDU_KEYWORDS)",
        "",
        "",
        "def is_known_section(section: str) -> bool:",
        '    """Return True when the specification lists the section."""',
        "    return normalise_key(section) in _NORMALISED_SECTIONS",
        "",
        "",
        "def keyword_spec(section: str, key: str) -> KeywordSpec | None:",
        '    """Return the keyword specification, or None when it is not listed."""',
        "    return _BY_NORMALISED_NAME.get("
        "(normalise_key(section), normalise_key(key)))",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--spec", type=Path, required=True, help="Path to mdu.json.")
    parser.add_argument(
        "--check", action="store_true", help="Fail if the module on disk differs."
    )
    args = parser.parse_args(argv)

    text = render_module(collect_keywords(read_spec(args.spec)))
    if args.check:
        current = (
            OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.is_file() else ""
        )
        if current != text:
            print(f"{OUTPUT_PATH} differs from the generated module.")
            return 1
        print(f"{OUTPUT_PATH} reproduces from the pinned specification.")
        return 0
    OUTPUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT_PATH}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
